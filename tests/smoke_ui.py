"""UI smoke test (local mock backend, phone viewport) + screenshots.
usage: (python3 -m http.server 8767 &) ; /workspace/.venv-pw/bin/python tests/smoke_ui.py [base_url]"""
import sys, os
from playwright.sync_api import sync_playwright
BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8767/"
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "screenshots")
os.makedirs(OUT, exist_ok=True)
errors, results = [], []
def ok(name, cond): results.append((name, bool(cond))); print(("PASS " if cond else "FAIL ") + name)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", headless=True)
    ctx = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, is_mobile=True, has_touch=True, locale="en-IE", service_workers="block")
    pg = ctx.new_page()
    pg.on("console", lambda m: m.type == "error" and errors.append(m.text)); pg.on("pageerror", lambda e: errors.append(str(e)))
    pg.on("dialog", lambda d: d.accept())
    pg.goto(BASE + "?backend=mock&today=2026-10-24&tab=kit"); pg.wait_for_selector(".stats")
    ok("header reg + date", "231-D-43971 · Saturday 24/10/2026" in pg.inner_text("#today"))
    t = pg.inner_text("#view")
    ok("sections", all(s in t for s in ["Glovebox / Centre console", "Cabin / Door pockets", "Boot", "Frunk", "Seasonal / Occasional"]))
    ok("UK words", all(s in t for s in ["Torch / head torch", "Small bin bag", "Hand sanitiser", "Driving licence", "2–3 litres"]))
    ok("critical badge + reason", pg.locator(".item", has_text="Compact umbrella").locator(".c-crit").count() == 1 and "Ireland rain" in pg.locator(".item", has_text="Compact umbrella").inner_text())
    ok("counts 0/45", "0/45" in pg.inner_text(".stats"))
    pg.screenshot(path=f"{OUT}/kit.png")
    um = pg.locator(".item", has_text="Compact umbrella")
    um.locator("[data-tick=packed]").tap()
    ok("in car implies have", um.locator("[data-tick=have]").get_attribute("aria-pressed") == "true")
    pg.locator(".item", has_text="Driving licence").locator("[data-tick=have]").tap()
    pg.locator(".item", has_text="Warning triangle").locator("[data-tick=packed]").tap()
    pg.locator(".item", has_text="Tissues").locator("[data-tick=packed]").tap()
    ok("counts 4 have / 3 packed", "4/45" in pg.inner_text(".stats") and "3/45" in pg.inner_text(".stats"))
    pg.click("[data-filter=buy]"); ok("to buy = 41", pg.locator(".item.kit").count() == 41)
    pg.click("[data-filter=pack]"); ok("not in car = licence", pg.locator(".item.kit").count() == 1 and "Driving licence" in pg.inner_text("#view"))
    pg.click("[data-filter=critical]"); ok("critical only = 15", pg.locator(".item.kit").count() == 15)
    pg.screenshot(path=f"{OUT}/kit-critical.png")
    pg.click("[data-filter=all]")
    # add / edit / delete
    pg.click("[data-add-item]"); pg.fill("#e-name", "Tyre pressure gauge"); pg.select_option("#e-section", "frunk"); pg.check("#e-crit"); pg.fill("#e-note", "test note")
    pg.click("#edit-form .primary"); pg.wait_for_selector(".item:has-text('Tyre pressure gauge')")
    ok("added item", "46" in pg.inner_text(".stats"))
    pg.locator(".item", has_text="Tyre pressure gauge").locator(".body").click(); pg.fill("#e-name", "Tyre pressure gauge (digital)"); pg.click("#edit-form .primary")
    pg.wait_for_selector(".item:has-text('(digital)')"); ok("edited item", True)
    pg.locator(".item", has_text="(digital)").locator(".body").click(); pg.click("[data-delete]"); pg.wait_for_timeout(300)
    ok("deleted item", pg.locator(".item", has_text="(digital)").count() == 0 and "/45" in pg.inner_text(".stats"))
    # kit check
    pg.click("[data-tab=check]"); pg.wait_for_selector("[data-check-start]")
    ok("start says 3 items", "3 items" in pg.inner_text("[data-check-start]"))
    pg.click("[data-check-start]"); pg.wait_for_selector(".card.one")
    first = pg.inner_text(".card.one .big"); ok("first item glovebox→cabin order (Tissues)", first == "Tissues")
    pg.screenshot(path=f"{OUT}/check-one.png")
    pg.click("[data-answer=ok]"); pg.click("[data-answer=missing]"); pg.click("[data-check-back]")
    ok("back returns to umbrella", pg.inner_text(".card.one .big") == "Compact umbrella")
    pg.click("[data-answer=missing]"); pg.click("[data-mode=list]"); pg.wait_for_selector(".crow")
    pg.screenshot(path=f"{OUT}/check-list.png")
    pg.click("[data-all-ok]"); pg.wait_for_selector(".summary")
    ok("summary lists umbrella missing", "1 missing" in pg.inner_text(".summary") and "Compact umbrella" in pg.inner_text(".summary"))
    pg.screenshot(path=f"{OUT}/check-summary.png")
    pg.click("[data-check-finish]"); pg.wait_for_selector("[data-check-start]")
    ok("last check date saved", "Last completed check: 24/10/2026 – 1 missing" in pg.inner_text("#view"))
    pg.click("[data-unpack-missing]"); pg.wait_for_timeout(300)
    pg.click("[data-tab=kit]"); ok("umbrella unticked in car", pg.locator(".item", has_text="Compact umbrella").locator("[data-tick=packed]").get_attribute("aria-pressed") == "false")
    # reset flow
    pg.click("[data-tab=check]"); pg.click("[data-check-start]"); pg.click("[data-answer=ok]"); pg.click("[data-check-reset]"); pg.wait_for_selector("[data-check-start]"); ok("reset check", True)
    # dates
    pg.click("[data-tab=dates]"); pg.wait_for_selector(".item")
    names = pg.locator(".list").first.locator(".name").all_inner_texts()
    ok("dates sorted", [n.split(" ")[0] for n in names] == ["Book", "Motor", "Basic", "First", "Car"])
    t = pg.inner_text("#view")
    ok("service shows January 2027 + reminder 01/12/2026", "January 2027" in t and "01/12/2026" in t and "in 69 days" in t)
    ok("80,000 km note", "80,000 km" in t and "29,000 km" in t)
    ok("recommended €85/€74", "about €85" in t and "about €74" in t and "Recommended by Tesla app" in t)
    pg.screenshot(path=f"{OUT}/dates.png", full_page=True)
    pg.locator(".item", has_text="Tyre rotation").locator(".tick").tap(); pg.wait_for_timeout(200)
    ok("tyre rotation done with date", "Done 24/10/2026" in pg.locator(".item", has_text="Tyre rotation").inner_text())
    pg.locator(".item", has_text="Motor tax").locator(".tick").tap(); pg.wait_for_timeout(200)
    ok("motor tax moved to Done fold", "Motor tax" not in pg.locator(".list").first.inner_text())
    pg.click("#undo"); pg.wait_for_timeout(300); ok("undo puts it back", "Motor tax" in pg.locator(".list").first.inner_text())
    pg.click("[data-add-date]"); pg.fill("#e-title", "Renew parking permit"); pg.fill("#e-due", "2026-11-15"); pg.fill("#e-remind", "2026-11-01"); pg.click("#edit-form .primary")
    pg.wait_for_selector(".item:has-text('Renew parking permit')")
    ok("added date sorts first", pg.locator(".list").first.locator(".name").first.inner_text() == "Renew parking permit")
    pg.goto(BASE + "?backend=mock&today=2026-12-02&tab=dates"); pg.wait_for_selector(".banner.remind")
    ok("reminder banner on 02/12/2026", "Book Tesla service" in " ".join(pg.locator(".banner.remind").all_inner_texts()) and "Renew parking permit" in " ".join(pg.locator(".banner.remind").all_inner_texts()))
    pg.screenshot(path=f"{OUT}/dates-reminder.png")
    # wash
    pg.click("[data-tab=wash]"); pg.wait_for_selector(".wash-step")
    ok("wash order", pg.locator(".wash-step").all_inner_texts() == [f"{i+1}\n{n}" for i, n in enumerate(["Roof", "Windows", "Bonnet", "Sides", "Boot", "Wheels"])] or [x.split("\n")[-1] for x in pg.locator(".wash-step").all_inner_texts()] == ["Roof", "Windows", "Bonnet", "Sides", "Boot", "Wheels"])
    for i in range(6): pg.locator(".wash-step").nth(i).tap(); pg.wait_for_timeout(80)
    pg.wait_for_timeout(300); ok("6 of 6 + last wash date", "6 of 6" in pg.inner_text("#view") and "Last full wash 02/12/2026" in pg.inner_text("#view"))
    pg.screenshot(path=f"{OUT}/wash.png")
    pg.click("[data-wash-reset]"); pg.wait_for_timeout(300); ok("reset wash", "0 of 6" in pg.inner_text("#view"))
    # persistence after reload
    pg.reload(); pg.wait_for_selector(".tabs [aria-selected=true]"); pg.click("[data-tab=kit]"); pg.wait_for_selector(".stats")
    ok("persisted after reload", "Last kit check 24/10/2026" in pg.inner_text(".stats"))
    b.close()
print("console errors:", errors)
fails = [n for n, c in results if not c]
print(f"{len(results) - len(fails)}/{len(results)} passed"); sys.exit(1 if fails or errors else 0)
